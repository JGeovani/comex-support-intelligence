BEGIN;

-- =============================================================================
-- 01. SESSION CONFIGURATION
-- =============================================================================

SET LOCAL search_path TO public;


-- =============================================================================
-- 02. BUSINESS TABLES
-- =============================================================================

-- 02.01. customers

CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_name VARCHAR(150) NOT NULL,
    customer_code VARCHAR(30) NOT NULL,
    contact_email VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_customers
        PRIMARY KEY (customer_id),

    CONSTRAINT uq_customers_customer_code
        UNIQUE (customer_code),

    CONSTRAINT ck_customers_customer_name_not_blank
        CHECK (customer_name ~ '[^[:space:]]'),

    CONSTRAINT ck_customers_customer_code_not_blank
        CHECK (customer_code ~ '[^[:space:]]')
);

-- 02.02. shipments

CREATE TABLE shipments (
    shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id BIGINT NOT NULL,
    shipment_reference VARCHAR(50) NOT NULL,
    origin_country CHAR(2) NOT NULL,
    destination_country CHAR(2) NOT NULL,
    departure_date DATE NOT NULL,
    arrival_date DATE,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_shipments
        PRIMARY KEY (shipment_id),

    CONSTRAINT fk_shipments_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT uq_shipments_shipment_reference
        UNIQUE (shipment_reference),

    CONSTRAINT uq_shipments_shipment_customer
        UNIQUE (shipment_id, customer_id),

    CONSTRAINT ck_shipments_reference_not_blank
        CHECK (shipment_reference ~ '[^[:space:]]'),

    CONSTRAINT ck_shipments_origin_country
        CHECK (origin_country COLLATE "C" ~ '^[A-Z]{2}$'),

    CONSTRAINT ck_shipments_destination_country
        CHECK (destination_country COLLATE "C" ~ '^[A-Z]{2}$'),

    CONSTRAINT ck_shipments_date_order
        CHECK (
            arrival_date IS NULL
            OR arrival_date >= departure_date
        ),

    CONSTRAINT ck_shipments_status
        CHECK (
            status IN (
                'PLANNED',
                'IN_TRANSIT',
                'ARRIVED',
                'CANCELLED'
            )
        )
);

-- 02.03. documents

CREATE TABLE documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    shipment_id BIGINT NOT NULL,
    document_type VARCHAR(30) NOT NULL,
    document_number VARCHAR(80),
    document_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_documents
        PRIMARY KEY (document_id),

    CONSTRAINT fk_documents_shipment
        FOREIGN KEY (shipment_id)
        REFERENCES shipments (shipment_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT ck_documents_document_type
        CHECK (
            document_type IN (
                'COMMERCIAL_INVOICE',
                'PACKING_LIST',
                'BILL_OF_LADING'
            )
        ),

    CONSTRAINT ck_documents_document_status
        CHECK (
            document_status IN (
                'PENDING',
                'RECEIVED',
                'VALIDATED',
                'REJECTED'
            )
        )
);


-- =============================================================================
-- 03. STAGING TABLE
-- =============================================================================

-- 03.01. shipment_staging

CREATE TABLE shipment_staging (
    staging_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    batch_id UUID NOT NULL,
    source_file TEXT,
    source_row_number INTEGER,
    shipment_reference TEXT,
    customer_code TEXT,
    departure_date_raw TEXT,
    arrival_date_raw TEXT,
    status_raw TEXT,
    raw_payload JSONB NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_shipment_staging
        PRIMARY KEY (staging_id),

    CONSTRAINT ck_shipment_staging_source_row_number
        CHECK (
            source_row_number IS NULL
            OR source_row_number > 0
        )
);


-- =============================================================================
-- 04. DATA QUALITY TABLE
-- =============================================================================

-- 04.01. data_quality_issues

CREATE TABLE data_quality_issues (
    issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    staging_id BIGINT,
    shipment_id BIGINT,
    rule_code VARCHAR(50) NOT NULL,
    severity VARCHAR(10) NOT NULL,
    affected_field VARCHAR(80),
    description TEXT NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,

    CONSTRAINT pk_data_quality_issues
        PRIMARY KEY (issue_id),

    CONSTRAINT fk_data_quality_issues_staging
        FOREIGN KEY (staging_id)
        REFERENCES shipment_staging (staging_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT fk_data_quality_issues_shipment
        FOREIGN KEY (shipment_id)
        REFERENCES shipments (shipment_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT ck_data_quality_issues_origin
        CHECK (
            staging_id IS NOT NULL
            OR shipment_id IS NOT NULL
        ),

    CONSTRAINT ck_data_quality_issues_severity
        CHECK (
            severity IN (
                'CRITICAL',
                'HIGH',
                'MEDIUM',
                'LOW'
            )
        ),

    CONSTRAINT ck_data_quality_issues_resolution_order
        CHECK (
            resolved_at IS NULL
            OR resolved_at >= detected_at
        )
);


-- =============================================================================
-- 05. SUPPORT TABLES
-- =============================================================================

-- 05.01. tickets

CREATE TABLE tickets (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id BIGINT NOT NULL,
    shipment_id BIGINT,
    issue_id BIGINT,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    priority VARCHAR(2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,

    CONSTRAINT pk_tickets
        PRIMARY KEY (ticket_id),

    CONSTRAINT fk_tickets_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT fk_tickets_shipment_customer
        FOREIGN KEY (shipment_id, customer_id)
        REFERENCES shipments (shipment_id, customer_id)
        MATCH SIMPLE
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT fk_tickets_issue
        FOREIGN KEY (issue_id)
        REFERENCES data_quality_issues (issue_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT ck_tickets_title_nonblank
        CHECK (title ~ '[^[:space:]]'),

    CONSTRAINT ck_tickets_description_nonblank
        CHECK (description ~ '[^[:space:]]'),

    CONSTRAINT ck_tickets_priority
        CHECK (
            priority IN (
                'P1',
                'P2',
                'P3',
                'P4'
            )
        ),

    CONSTRAINT ck_tickets_status
        CHECK (
            status IN (
                'OPEN',
                'IN_ANALYSIS',
                'RESOLVED',
                'CLOSED'
            )
        ),

    CONSTRAINT ck_tickets_resolution_order
        CHECK (
            resolved_at IS NULL
            OR resolved_at >= created_at
        ),

    CONSTRAINT ck_tickets_status_resolution
        CHECK (
            (
                status IN ('OPEN', 'IN_ANALYSIS')
                AND resolved_at IS NULL
            )
            OR
            (
                status IN ('RESOLVED', 'CLOSED')
                AND resolved_at IS NOT NULL
            )
        )
);

-- 05.02. ticket_history

CREATE TABLE ticket_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ticket_id BIGINT NOT NULL,
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    change_note TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by VARCHAR(100) NOT NULL,

    CONSTRAINT pk_ticket_history
        PRIMARY KEY (history_id),

    CONSTRAINT fk_ticket_history_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES tickets (ticket_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,

    CONSTRAINT ck_ticket_history_previous_status
        CHECK (
            previous_status IS NULL
            OR previous_status IN (
                'OPEN',
                'IN_ANALYSIS',
                'RESOLVED',
                'CLOSED'
            )
        ),

    CONSTRAINT ck_ticket_history_new_status
        CHECK (
            new_status IN (
                'OPEN',
                'IN_ANALYSIS',
                'RESOLVED',
                'CLOSED'
            )
        ),

    CONSTRAINT ck_ticket_history_changed_by_nonblank
        CHECK (changed_by ~ '[^[:space:]]')
);


-- =============================================================================
-- 06. INDEXES
-- =============================================================================

-- 06.01. Foreign key indexes

CREATE INDEX idx_shipments_customer_id
    ON shipments (customer_id);

CREATE INDEX idx_documents_shipment_type
    ON documents (shipment_id, document_type);

CREATE INDEX idx_data_quality_issues_staging_id
    ON data_quality_issues (staging_id);

CREATE INDEX idx_data_quality_issues_shipment_id
    ON data_quality_issues (shipment_id);

CREATE INDEX idx_tickets_customer_id
    ON tickets (customer_id);

CREATE INDEX idx_tickets_shipment_customer
    ON tickets (shipment_id, customer_id);

CREATE INDEX idx_tickets_issue_id
    ON tickets (issue_id);

CREATE INDEX idx_ticket_history_ticket_changed_at
    ON ticket_history (ticket_id, changed_at);

-- 06.02. Operational indexes

CREATE INDEX idx_shipment_staging_batch_reference
    ON shipment_staging (batch_id, shipment_reference);

CREATE INDEX idx_tickets_status_priority_created_at
    ON tickets (status, priority, created_at);

CREATE INDEX idx_data_quality_issues_active_severity_detected_at
    ON data_quality_issues (severity, detected_at)
    WHERE resolved_at IS NULL;

-- 06.03. Data quality deduplication indexes

CREATE UNIQUE INDEX uq_data_quality_issues_active_staging
    ON data_quality_issues (
        staging_id,
        rule_code,
        affected_field
    )
    NULLS NOT DISTINCT
    WHERE resolved_at IS NULL
      AND staging_id IS NOT NULL;

CREATE UNIQUE INDEX uq_data_quality_issues_active_shipment
    ON data_quality_issues (
        shipment_id,
        rule_code,
        affected_field
    )
    NULLS NOT DISTINCT
    WHERE resolved_at IS NULL
      AND staging_id IS NULL;


-- =============================================================================
-- 07. TRANSACTION COMPLETION
-- =============================================================================

COMMIT;